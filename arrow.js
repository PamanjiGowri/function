
// i. Function Declaration
function multiply(a, b) {
    return a * b;
}

// ii. Regular Function
function add(a, b) {
    return a + b;
}

// iii. Arrow Function
const square = (a, b) => a * b;

// Display output in console
console.log("Function Declaration:", multiply(10, 5));
console.log("Function Definition:", add(60, 3));
console.log("Arrow Function:", square(5, 5));